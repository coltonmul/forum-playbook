#!/usr/bin/env python3
"""build-core-icons.py: writes core-icons.js, the Phosphor thin drawings the homepage's Core Resources groups use.
VERSION 1.1.0 (2026-11-20)
  1.1.0: chat-circle-dots (1000greatquestions.com), files (Templates and Worksheets), arrow-square-out (opens an outside site).

  /opt/homebrew/bin/python3 tools/build-core-icons.py

One map, one place: every icon a homepage card, row, group head or format button wears is named in ICONS below and
drawn by ~/Sites/brand-assets/icons/icon.py (Phosphor, thin). config.js refers to them by name. Add a name here,
rerun, and it is available to config.js. The script stops if a name does not exist.
"""
import json, os, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICON_PY = os.path.expanduser("~/Sites/brand-assets/icons/icon.py")

ICONS = [
    # the things
    "timer", "table", "percent", "scroll", "chats-circle", "handshake", "clock-countdown", "scales",
    "chart-pie-slice", "flower-lotus", "star-four", "chat-circle-dots",
    # the group heads
    "toolbox", "path", "mountains", "files",
    # the formats and actions
    "browser", "file-pdf", "play-circle", "file-doc", "file-xls", "file-md", "google-drive-logo", "copy",
    "device-mobile", "arrow-up-right", "arrow-square-out", "download-simple", "eye", "app-store-logo",
]

out = {}
for name in ICONS:
    try:
        svg = subprocess.check_output(["/opt/homebrew/bin/python3", ICON_PY, "svg", name, "--weight", "thin", "--size", "32"],
                                      cwd=os.path.dirname(ICON_PY), stderr=subprocess.STDOUT).decode().strip()
    except subprocess.CalledProcessError as e:
        sys.exit(f"build-core-icons: no such icon {name!r}: {e.output.decode()[:200]}")
    if not svg.startswith("<svg"):
        sys.exit(f"build-core-icons: unexpected output for {name!r}")
    out[name] = svg.replace("<svg ", '<svg focusable="false" ', 1)

js = ("// core-icons.js: GENERATED by tools/build-core-icons.py, never hand-edited. Phosphor thin (MIT).\n"
      "const CORE_ICONS = " + json.dumps(out, indent=0, sort_keys=True) + ";\n")
if "\u2014" in js: sys.exit("guard failed: em dash")
open(os.path.join(ROOT, "core-icons.js"), "w").write(js)
print("built core-icons.js:", len(out), "icons,", len(js), "bytes")
